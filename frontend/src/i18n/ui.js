/** Look up a UI string, falling back to English for any key a locale misses. */
export function t(language, key) {
  const table = STRINGS[language] ?? STRINGS.en
  return table[key] ?? STRINGS.en[key] ?? key
}

export function profileLabel(language, profile) {
  const table = STRINGS[language] ?? STRINGS.en
  return table.profiles?.[profile] ?? STRINGS.en.profiles[profile] ?? profile
}

export default STRINGS

/** Localised hazard name. Falls back to the backend's English key. */
export function hazardLabel(language, hazard) {
  if (!hazard) return ''
  const table = STRINGS[language]?.hazards ?? STRINGS.en.hazards
  return table[hazard] ?? STRINGS.en.hazards[hazard] ?? hazard
}
